export const DICTS: Record<Lang, Dict> = { pt, en }

export type Vars = Record<string, string | number>

export function translate(lang: Lang, key: string, vars?: Vars): string {
  const s = DICTS[lang][key] ?? DICTS.pt[key] ?? key
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s
}

export function isLang(v: unknown): v is Lang {
  return v === "pt" || v === "en"
}

export function locale(lang: Lang) {
  return lang === "en" ? "en-US" : "pt-BR"
}

/** Error carrying a message key so API routes can render it in the caller's language. */
export class AppError extends Error {
  constructor(
    public key: string,
    public vars: Vars = {},
  ) {
    super(translate("pt", key, vars))
  }
}

export function requestLang(req: Request): Lang {
  const h = req.headers.get(LANG_HEADER)
  if (isLang(h)) return h
  return /^en/i.test(req.headers.get("accept-language") ?? "") ? "en" : "pt"
}

export function errorText(e: unknown, lang: Lang, fallbackKey?: string): string {
  if (e instanceof AppError) return translate(lang, e.key, e.vars)
  if (e instanceof Error) return e.message
  return fallbackKey ? translate(lang, fallbackKey) : String(e)
}
